const now = Date.now();
const day = 86400000;
const iso = (daysAgo: number, hour = 10) => {
  const d = new Date(now - daysAgo * day);
  d.setHours(hour, 0, 0, 0);
  return d.toISOString();
};
const future = (days: number, hour = 10) => {
  const d = new Date(now + days * day);
  d.setHours(hour, 0, 0, 0);
  return d.toISOString();
};

